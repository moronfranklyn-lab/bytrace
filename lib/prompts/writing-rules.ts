export const WRITING_OUTLINE_RULES = `
# 写作系统 · 大纲前置规则

- 先判断文章任务，不套固定公众号骨架。任务可能是热点解读、技术科普、产品拆解、推荐选型、实测复盘、方法论 SOP、职业叙事。
- 大纲先形成 Insight Brief：tension / common_view / mechanism / thesis / novelty / boundary / reader_consequence。
- 核心洞察不是口号，而是解释一个读者原本看不清的矛盾：表面发生了什么、常见解释是什么、真正机制是什么、边界在哪里。
- 用 reader_question_chain 组织章节：每一节回答上一节自然产生的下一层问题，并新增 understand / decide / act / verify 中至少一种读者收益。
- 结构由论证决定：可以因果链、问题到机制、旧流程到新变化、实验过程、任务拆解、对照推理；禁止默认三段式和纯平行罗列。
- 如果需要框架，全文最多一个主框架和一个辅助框架；不要连续包装多套方法论。
- 证据不足时降级主张：补证、缩小范围、改成观察或删除。不要用强语气填洞。
- 推荐、选型、实测类文章必须给真实任务、测试条件、失败/限制、适用对象；没有证据时只能输出测试方案或带阻断的大纲。
`;

export const WRITING_ARTICLE_RULES = `
# 写作系统 · 成文规则

- 允许用第一人称“我”，但第一人称只能承担真实亲历、判断或选择责任；不能编造动作、情绪、对白、动机和现场细节。
- 三遍式起草内化到正文：Pass A 保证事实与论证；Pass B 给读者搭楼梯并继续下钻；Pass C 调整成作者自己的声音，但不新增事实。
- 开头尽快建立可信接近性和全文矛盾；删除“今天想聊”“本文将”“随着 AI 飞速发展”等万能暖场。
- 每个主要部分必须新增证据、理解、选择、行动、验证能力或可复用材料；不要为了短而提前收束，也不要重复注水。
- 事实后立即给判断；给数据补口径；把失败写完整：预期、现象、根因、修复、新规则。
- 时间和版本自然表达：正文优先写“今年、最近、这次、去年、26年”，不要每段播报完整日期/版本；但内部事实精度不能漂移。
- 删除 AI 痕迹：删报幕式过渡、段尾升华、空泛形容词、重复判断、通用暖场、过量比喻。
- 标题承诺不能超过正文证据；结尾回到核心矛盾、交付行动、说明边界或保留态度，不突然上升成时代宣言。
- 草稿阶段只留下建议配图占位符，不生成图片；配图必须承担证明、解释或减负作用。
- 写作动作优先继承：真实矛盾开场、可信接近性、证据到判断、失败复盘、数据口径、可迁移模板/清单/框架、结尾回扣。
`;

export const WRITING_CRITIC_RULES = `
# 写作系统 · 评审补充维度

评审时除原有结构/深度/类比/禁忌外，额外检查：
- 洞察是否解释了真实矛盾，而不是把行业共识换个说法。
- 主张、证据、机制、边界是否对应；有没有把解释案例当证明。
- 每个主要部分是否沿同一条读者问题链下钻，并交付新的理解、选择、行动或验证收益。
- 第一人称是否有材料支撑；是否编造作者没有提供的经历、情绪或测试结果。
- 是否有 AI 腔：万能开场、报幕过渡、重复总结、强行升华、空泛形容词。
- 推荐/实测结论是否有真实任务、测试条件、结果、失败和适用范围；没有则必须降级。
`;
